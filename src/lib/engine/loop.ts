// ─────────────────────────────────────────────────────────────────────────────
// Паузы для event loop в длинных операциях (сборки, импорт дампа).
//
// Синхронные фазы сборки (слияние 478k правил, сортировка 6 млн доменов,
// рендер файла) блокируют event loop: на это время Node не обслуживает
// НИКАКИЕ запросы — опрос GET /api/build/progress «зависает», UI показывает
// непонятный статус, healthcheck может не уложиться в таймаут.
// yieldToLoop() отдаёт управление событиям (setImmediate — следующий оборот
// цикла, микрозадачи дождутся), чтобы интерактивные запросы пробивались
// между чанками работы. Вставляется каждые N обрабатываемых элементов.
// ─────────────────────────────────────────────────────────────────────────────

/** Отдать управление event loop (один оборот): асинхронные запросы обслуживаются */
export function yieldToLoop(): Promise<void> {
  return new Promise((resolve) => setImmediate(resolve))
}

/** Пауза в мс (для разгрузки БД между батчами тяжёлой сборки) */
export function sleepMs(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms))
}

/**
 * Прогнать body для каждой порции элементов с yield между порциями.
 * Порции — ссылочные (не копируют массив), размер подобран так, чтобы
 * синхронный кусок не превышал ~50-100 мс.
 */
export const YIELD_CHUNK = 25_000

/** Вызвать yieldToLoop() каждые chunk элементов — числовой счётчик ведёт вызывающий */
export async function maybeYield(processed: number, chunk: number = YIELD_CHUNK): Promise<void> {
  if (chunk > 0 && processed % chunk === 0) await yieldToLoop()
}
